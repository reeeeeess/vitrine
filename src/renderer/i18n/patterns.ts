// The English of the sentences Vitrine composes (a name, a number, a date inside a sentence), tried in order
// when the whole text is not in en.json. `tr` translates a part that is itself a known text (a period, a
// reason, a source), and leaves anything else (a title, an artist) as it is.
export type Translate = (text: string) => string;
export type Pattern = [RegExp, (parts: string[], tr: Translate) => string];

/** a number as Vitrine writes it, in either language: "12", "1 234", "1,234" */
const N = "(\\d[\\d\\s\\u202f.,]*)";
/** "" for one, "s" for any other number */
const s = (n: string) => (n.replace(/\D/g, "") === "1" ? "" : "s");
const quote = (name: string) => `“${name}”`;
const re = (source: string) => new RegExp(`^${source.replace(/\{n\}/g, N)}$`, "s");

